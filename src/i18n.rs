//! Internationalization (i18n) support for SQL Editor.
//! Full support for Polish (pl), English (en), German (de), and Spanish (es).

#![allow(dead_code)]

use std::sync::RwLock;

pub const LANGUAGES: &[(&str, &str)] = &[
    ("pl", "Polski"),
    ("en", "English"),
    ("de", "Deutsch"),
    ("es", "Español"),
];

static CURRENT_LANG: RwLock<String> = RwLock::new(String::new());

pub fn get_language() -> String {
    let guard = CURRENT_LANG.read().unwrap();
    if guard.is_empty() {
        "pl".to_string()
    } else {
        guard.clone()
    }
}

pub fn set_language(lang: &str) {
    let mut guard = CURRENT_LANG.write().unwrap();
    let normalized = match lang {
        "pl" | "Polski" => "pl",
        "en" | "English" => "en",
        "de" | "Deutsch" => "de",
        "es" | "Español" => "es",
        _ => "en",
    };
    *guard = normalized.to_string();
}

pub fn language_name(code: &str) -> &'static str {
    for &(c, name) in LANGUAGES {
        if c == code {
            return name;
        }
    }
    "Polski"
}

pub fn language_code_from_name(name: &str) -> &'static str {
    for &(c, n) in LANGUAGES {
        if n == name || c == name {
            return c;
        }
    }
    "pl"
}

fn get_dict(lang: &str) -> &'static [(&'static str, &'static str)] {
    match lang {
        "en" => EN_TRANSLATIONS,
        "de" => DE_TRANSLATIONS,
        "es" => ES_TRANSLATIONS,
        _ => PL_TRANSLATIONS,
    }
}

pub fn tr(key: &str) -> String {
    let lang = get_language();
    let dict = get_dict(&lang);
    if let Some(&(_, val)) = dict.iter().find(|(k, _)| *k == key) {
        return val.to_string();
    }
    // Fallback to English
    if let Some(&(_, val)) = EN_TRANSLATIONS.iter().find(|(k, _)| *k == key) {
        return val.to_string();
    }
    key.to_string()
}

pub fn tr_fmt(key: &str, args: &[(&str, &str)]) -> String {
    let mut res = tr(key);
    for (param, val) in args {
        let pattern = format!("{{{}}}", param);
        res = res.replace(&pattern, val);
    }
    res
}

